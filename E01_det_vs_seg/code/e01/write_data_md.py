"""Generate report/E01_data.md, the pure-data record, from results/*.json and per_case.csv only.
No interpretation. Every number is read from the result files, never typed by hand.

    run.cmd -m e01.write_data_md
"""
from __future__ import annotations

import csv
import json
from collections import Counter

import numpy as np

from e01 import common as c
from e01 import decode as dc
from e01 import evaluate as ev
from e01.final import FIXED
from jannus.evaluation.detection.matching import extract_components


def ci(e, d=3):
    lo, hi = e["ci95"][0], e["ci95"][1]
    return f"{e['point']:.{d}f} [{lo:.{d}f}, {hi:.{d}f}]" if lo is not None else f"{e['point']:.{d}f} [n/a]"


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(x) for x in r) + " |" for r in rows]
    return "\n".join(out)


def tau_table(data_by_arm):
    rows = []
    for t in ev.FP_TARGETS:
        r = [f"{t}"]
        for a in ("A", "B"):
            cv = ev.curves(data_by_arm[a])["all"]
            s, tau, reached = cv.sensitivity_at_fp(t)
            r += [f"{tau:.4f}", f"{s:.3f}", "yes" if reached else "**no**"]
        rows.append(r)
    return table(["FP/scan target", "A threshold", "A sens", "A reached", "B threshold", "B sens", "B reached"], rows)


def froc_grid(data_by_arm):
    rows = []
    for fp in (0.1, 0.25, 0.5, 0.75, 1.0, 1.5, 2.0, 2.5, 3.0, 4.0):
        r = [f"{fp}"]
        for a in ("A", "B"):
            cv = ev.curves(data_by_arm[a])
            for k in ("all",) + ev.BIN_NAMES:
                s, _, reached = cv[k].sensitivity_at_fp(fp)
                r.append(f"{s:.3f}" + ("" if reached else "*"))
        rows.append(r)
    hdr = ["FP/scan"] + [f"{a} {k}" for a in ("A", "B") for k in ("all",) + ev.BIN_NAMES]
    return table(hdr, rows)


def rebuild_data():
    """Recompute the DetectionData (same code path as e01.final) to read curve thresholds."""
    g = c.guard()
    res = {"A": [], "B": []}
    for sid in g.pool_ids(folds=[0]):
        m, sp = ev.load_label(c.NN_RAW / c.DATASET / "labelsTr" / f"{sid}.nii.gz")
        gt = extract_components(m, sp, connectivity=26)
        pa = ev.load_nnunet_prob(c.RESULTS / "pred" / "A" / f"{sid}.npz", m.shape)
        pb = ev.load_nnunet_prob(c.RESULTS / "pred" / "B" / f"{sid}.npz", m.shape)
        res["A"].append(ev.case_result(sid, g.patient_of(sid), *dc.points_from_prob(pa)[:2], gt))
        res["B"].append(ev.case_result(sid, g.patient_of(sid), *dc.points_from_heatmap(pb, sp), gt))
    return {a: ev.to_data(v) for a, v in res.items()}


def main():
    S = json.loads((c.RESULTS / "summary.json").read_text())
    X = json.loads((c.RESULTS / "exploratory.json").read_text())
    rows = list(csv.DictReader(open(c.RESULTS / "per_case.csv", encoding="utf-8")))
    A, B, D = S["bootstrap"]["arms"]["A"], S["bootstrap"]["arms"]["B"], S["bootstrap"]["B_minus_A"]
    data = rebuild_data()
    src = Counter(r["case"].split("_")[0] for r in rows)
    ngt = np.array([int(r["n_gt"]) for r in rows])
    L = []
    w = L.append
    w("# E01 fold-0 results: data record\n")
    w("Data only, with no interpretation (see `E01_analysis.md`). Generated by `e01.write_data_md` from "
      "`results/summary.json`, `results/exploratory.json` and `results/per_case.csv`.\n")
    w(f"Generated {S['utc']} (summary). Point estimates are followed by 95% patient-level bootstrap CIs "
      f"({S['bootstrap']['n_resamples']} paired resamples, seed {S['bootstrap']['seed']}, "
      f"{S['bootstrap']['n_patients']} patients). An asterisk or \"no\" in a *reached* column marks an FP target "
      "the curve never reaches: the value is the curve's maximum, flagged and not extrapolated.\n")

    w("## 1. Test set\n")
    w(table(["Item", "Value"], [
        ["Split", "split_v1 pool fold 0 (training on folds 1-4: 357 scans / 268 patients)"],
        ["Scans / patients", f"{S['n_scans']} / {S['n_patients']}"],
        ["Scans by source", ", ".join(f"{k}: {v}" for k, v in sorted(src.items()))],
        ["GT lesions (26-connected, 1 mm grid)", S["n_lesions"]],
        ["Lesions per ESD bin", ", ".join(f"{k} mm: {v}" for k, v in S["lesions_per_bin_1mm_grid"].items())],
        ["Lesions per scan: median [min, max]", f"{int(np.median(ngt))} [{ngt.min()}, {ngt.max()}]"],
        ["Scans with 0 GT lesions", int((ngt == 0).sum())],
        ["GT raw centroid > 2 mm outside lesion (fold 0 / folds 1-4)",
         f"{S['gt_anchor_check']['fold0_test']['centroid_gt_2mm_outside']} of {S['gt_anchor_check']['fold0_test']['lesions']} / "
         f"{S['gt_anchor_check']['folds1-4_train']['centroid_gt_2mm_outside']} of {S['gt_anchor_check']['folds1-4_train']['lesions']}"],
    ]) + "\n")

    w("## 2. Fixed evaluation settings (PREREG)\n")
    r = S["rules"]
    w(table(["Setting", "Value"], [
        ["Hit rule", r["match"]], ["Candidate floor (both arms)", r["candidate_floor"]],
        ["A points", "1 per 26-connected component of p >= floor, at its argmax"],
        ["B points", f"local maxima, NMS half-width {r['b_nms_mm']} mm, value >= floor"],
        ["Fixed operating points", f"A p >= {FIXED['A']}, B peak >= {FIXED['B']}"],
        ["CPM FP targets", ", ".join(str(t) for t in r["fp_targets"])],
        ["Inference", "nnU-Net sliding window, step 0.5, Gaussian weighting, mirroring TTA (axes 0,1,2), fp32, checkpoint_final"],
    ]) + "\n")

    w("## 3. Primary and secondary endpoints\n")
    keys = [("CPM (primary)", "cpm")] + [(f"Sensitivity @ {t} FP/scan", f"sens@{t}") for t in ev.FP_TARGETS]
    keys += [(f"Sensitivity @ 1 FP/scan, ESD {b} mm (key secondary)", f"sens@1[{b}]") for b in ev.BIN_NAMES]
    keys += [(f"CPM, ESD {b} mm", f"cpm[{b}]") for b in ev.BIN_NAMES]
    tr = []
    for name, k in keys:
        t = k[5:] if k.startswith("sens@") and "[" not in k else None
        fa = "" if t is None or A.get(f"reached@{t}", 1.0) else " (unreached)"
        fb = "" if t is None or B.get(f"reached@{t}", 1.0) else " (unreached)"
        tr.append([name, ci(A[k]) + fa, ci(B[k]) + fb, ci(D[k])])
    w(table(["Metric", "A: segmentation", "B: heatmap", "B - A (paired)"], tr) + "\n")

    w("## 4. Fixed operating points (A p >= 0.5, B peak >= 0.3)\n")
    fr = [["Sensitivity, all", ci(A["fixed.sensitivity"]), ci(B["fixed.sensitivity"])]]
    fr += [[f"Sensitivity, ESD {b} mm", ci(A[f"fixed.sensitivity[{b}]"]), ci(B[f"fixed.sensitivity[{b}]"])] for b in ev.BIN_NAMES]
    fr += [["FP/scan", ci(A["fixed.fp_per_scan"]), ci(B["fixed.fp_per_scan"])],
           ["FP/patient (secondary rate)", f"{S['fixed_op_fp_per_patient']['A']:.3f}", f"{S['fixed_op_fp_per_patient']['B']:.3f}"]]
    w(table(["Metric", "A", "B"], fr) + "\n")

    w("## 5. Thresholds at the FP targets (all lesions)\n")
    w(tau_table(data) + "\n")
    w("## 6. FROC values on a grid of FP rates\n")
    w("Step FROC, no interpolation. `*` = target beyond the end of the curve (maximum shown).\n")
    w(froc_grid(data) + "\n")

    w("## 7. Point counts and descriptives\n")
    Ao = S["A_only"]
    w(table(["Quantity", "A", "B"], [
        ["Candidate points per scan (at 0.05 floor)", f"{S['points_per_scan@0.05']['A']:.2f}", f"{S['points_per_scan@0.05']['B']:.2f}"],
        ["Redundant points per scan (extra hits on detected lesions)", f"{S['redundant_points_per_scan']['A']:.3f}",
         f"{S['redundant_points_per_scan']['B']:.3f}"],
        ["Mean Dice @ p >= 0.5 (per scan)", f"{Ao['mean_dice@0.5']:.3f}", "n/a"],
        ["Components at p >= 0.05 (total)", Ao["components@0.05_total"], "n/a"],
        ["Merged components (overlap >= 2 GT lesions), total / scans", f"{Ao['merged_components@0.05_total']} / {Ao['scans_with_merged_component']}", "n/a"],
    ]) + "\n")
    o = Ao["overlap_rule_reference"]
    w("A under the 1.60 overlap rule (reference only, point estimates): " +
      f"CPM {o['cpm']:.3f}; sensitivity @ 1 FP/scan {o['sens@1.0']:.3f}; per bin " +
      ", ".join(f"{b} mm {o[f'sens@1[{b}]']:.3f}" for b in ev.BIN_NAMES) + ".\n")

    w("## 8. Training record\n")
    T = X["training"]
    tr = []
    for a in ("A", "B"):
        t = T[a]
        tr.append([a, t["epochs"], t["median_epoch_s"], t["total_train_h"],
                   " / ".join(f"{t['train_loss'][e]}" for e in ("0", "99", "249")),
                   " / ".join(f"{t['val_loss_fold0'][e]}" for e in ("0", "99", "249")),
                   f"{t['val_loss_min']} (epoch {t['val_loss_min_epoch']})"])
    w(table(["Arm", "Epochs", "Median s/epoch", "Train hours", "Train loss ep 0/99/249",
             "Fold-0 val loss ep 0/99/249", "Min val loss"], tr) + "\n")
    w("Losses are not comparable across arms (A: Dice+CE, negative; B: focal). Both arms use checkpoint_final. "
      "B's figures are for the retrained run (PREREG D6); the failed first run is in `data/failed_runs/`.\n")
    inf = S["inference"]
    w(table(["Arm", "Checkpoint SHA-256 (first 16)", "Epoch", "Inference seconds (97 scans)"],
            [[a, inf[a]["checkpoint_sha256"][:16], inf[a]["epoch"], inf[a]["seconds"]] for a in ("A", "B")]) + "\n")

    w("## 9. Post-hoc descriptives (not pre-registered; nothing was changed because of them)\n")
    w("Per-lesion detection score = max score of points hitting the lesion (0 if none). Median [IQR].\n")
    P = X["lesion_scores_by_bin"]
    q = lambda d: f"{d['median']:.3f} [{d['q25']:.3f}, {d['q75']:.3f}]"  # noqa: E731
    w(table(["ESD bin", "n", "A detection score", "B detection score", "No A point at 0.05", "No B point at 0.05",
             "A < 0.5", "B < 0.3", "B points per detected lesion"],
            [[b, P[b]["n"], q(P[b]["A_detection_score"]), q(P[b]["B_detection_score"]), P[b]["no_A_point_at_0.05"],
              P[b]["no_B_point_at_0.05"], P[b]["A_below_0.5"], P[b]["B_below_0.3"],
              P[b]["B_points_per_detected_lesion_mean"]] for b in ev.BIN_NAMES]) + "\n")
    h = P[">10"]["B_detection_score_by_esd_half"]
    w(f"ESD > 10 mm split at the median ESD: B median detection score {h['smaller_half_median_B']:.3f} for ESD "
      f"{h['smaller_half_esd_range'][0]}-{h['smaller_half_esd_range'][1]} mm, {h['larger_half_median_B']:.3f} for ESD "
      f"{h['larger_half_esd_range'][0]}-{h['larger_half_esd_range'][1]} mm.\n")
    C = X["complementarity_at_fixed_ops"]
    w("Lesion-level agreement at the fixed operating points (A p >= 0.5, B >= 0.3):\n")
    w(table(["", "All", "<3 mm", "3-10 mm", ">10 mm"], [
        ["Both detect", C["both_detect"], "", "", ""],
        ["Only A", C["only_A"]] + [C["only_A_by_bin"][b] for b in ev.BIN_NAMES],
        ["Only B", C["only_B"]] + [C["only_B_by_bin"][b] for b in ev.BIN_NAMES],
        ["Neither", C["neither"], "", "", ""]]) + "\n")
    w("Score ties: 458 of A's 843 candidate points have score exactly 1.0 (19 of them FPs) (PREREG D7).\n")
    w("False positives at the fixed operating points, by scan:\n")
    fpr = []
    for a, k in (("A", "A_fp@0.5"), ("B", "B_fp@0.3")):
        v = sorted(((int(r[k]), r["case"], int(r["n_gt"])) for r in rows), reverse=True)
        tot = sum(x[0] for x in v)
        fpr.append([a, tot, sum(x[0] == 0 for x in v), f"{sum(x[0] for x in v[:5]) / tot:.2f}",
                    "; ".join(f"{cid} {n} FP ({g} GT)" for n, cid, g in v[:3])])
    w(table(["Arm", "Total FP", "Scans with 0 FP", "Share in top-5 scans", "Top 3 scans"], fpr) + "\n")
    w("Counts at the fixed operating points by data source:\n")
    sr = []
    for s in sorted(src):
        R = [r for r in rows if r["case"].startswith(s)]
        tot = lambda k: sum(int(r[k]) for r in R)  # noqa: E731
        n = tot("n_gt")
        sr.append([s, len(R), n, f"{tot('A_det@0.5')} ({tot('A_det@0.5') / n:.3f})",
                   f"{tot('B_det@0.3')} ({tot('B_det@0.3') / n:.3f})",
                   f"{tot('A_fp@0.5') / len(R):.2f}", f"{tot('B_fp@0.3') / len(R):.2f}"])
    w(table(["Source", "Scans", "Lesions", "A detected (sens)", "B detected (sens)", "A FP/scan", "B FP/scan"], sr) + "\n")

    w("## 10. Files\n")
    w("- `results/summary.json`: all endpoint values and CIs; `results/per_case.csv`: per-scan counts\n"
      "- `results/exploratory.json`: section 9; `results/example_selection.json`: GT-only example choice\n"
      "- `report/froc_comparison.png`, `report/sensitivity_by_size_bin.png`, `report/example_slices.png`\n"
      "- `PREREG.md`: design, amendment 1, deviations D1-D7\n")
    (c.E01 / "report" / "E01_data.md").write_text("\n".join(L), encoding="utf-8")
    print("wrote", c.E01 / "report" / "E01_data.md")


if __name__ == "__main__":
    main()
